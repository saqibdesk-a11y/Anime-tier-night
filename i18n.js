  function lookupSingle(core){
    if(Object.prototype.hasOwnProperty.call(AR, core)) return AR[core];
    const norm = core.replace(/’/g, "'");
    if(norm !== core && Object.prototype.hasOwnProperty.call(AR, norm)) return AR[norm];
    for(const [re, fn] of RULES){
      const m = norm.match(re);
      if(m) return fn(...m);
    }
    return null;
  }

  function translateText(str){
    if(lang !== "ar" || !str) return str;
    const lead = (str.match(/^\s*/) || [""])[0];
    const trail = (str.match(/\s*$/) || [""])[0];
    const core = str.trim();
    if(!core) return str;
    const hit = lookupSingle(core);
    if(hit !== null) return lead + hit + trail;
    // Compound "A · B" segments
    if(core.includes(" · ")){
      const parts = core.split(" · ");
      const mapped = parts.map(p => lookupSingle(p) ?? p);
      if(mapped.some((v, i) => v !== parts[i])) return lead + mapped.join(" · ") + trail;
    }
    // Multi-sentence notices ("Each team needs at least one guesser. Each team needs a spymaster.")
    if(core.includes(". ")){
      const sents = core.split(/(?<=\.)\s+/);
      if(sents.length > 1){
        const mapped = sents.map(s => lookupSingle(s) ?? lookupSingle(s.replace(/\.$/, "")) ?? s);
        if(mapped.some((v, i) => v !== sents[i])) return lead + mapped.join(" ") + trail;
      }
    }
    return str;
  }

  function skipElement(el){
    if(!el || el.nodeType !== 1) return false;
    const tag = el.tagName;
    if(tag === "SCRIPT" || tag === "STYLE" || tag === "TEXTAREA" || tag === "CODE" || tag === "PRE" || tag === "SVG") return true;
    if(el.hasAttribute("data-no-i18n") || el.classList.contains("code") || el.classList.contains("rev-title") || el.classList.contains("rev-artst")) return true;
    if(el.classList.contains("nm") && !(el.textContent || "").includes("(you)")) return true;
    return false;
  }

  let applying = false;
  function translateNode(root){
    if(!root) return;
    const walk = node => {
      if(node.nodeType === 3){
        const parent = node.parentElement;
        if(!parent || skipElement(parent)) return;
        const cur = node.nodeValue;
        if(!cur || !cur.trim()) return;
        let base = origText.get(node);
        if(base === undefined){
          origText.set(node, cur);
          base = cur;
        }
        const target = lang === "ar" ? translateText(base) : base;
        if(node.nodeValue !== target) node.nodeValue = target;
        return;
      }
      if(node.nodeType !== 1 || skipElement(node)) return;
      for(const a of ATTRS){
        if(!node.hasAttribute(a)) continue;
        let map = origAttr.get(node);
        if(!map){ map = {}; origAttr.set(node, map); }
        if(map[a] === undefined) map[a] = node.getAttribute(a);
        const target = lang === "ar" ? translateText(map[a]) : map[a];
        if(node.getAttribute(a) !== target) node.setAttribute(a, target);
      }
      for(let c = node.firstChild; c; c = c.nextSibling) walk(c);
    };
    applying = true;
    try{ walk(root); } finally { applying = false; }
  }

  function syncDoc(){
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.querySelectorAll(".lang-btn").forEach(b => {
      b.textContent = lang === "ar" ? "EN" : "عربي";
      b.title = lang === "ar" ? "Switch to English" : "التبديل إلى العربية";
      b.setAttribute("aria-label", b.title);
    });
    if(document.body) translateNode(document.body);
  }

  function set(next){
    const n = next === "ar" ? "ar" : "en";
    if(n === lang) return;
    lang = n;
    try{
      localStorage.setItem(KEY, lang);
      localStorage.setItem("howtoLang", lang);
    }catch(e){}
    if(window.Juice && Juice.sfx) Juice.sfx.click();
    syncDoc();
    listeners.forEach(f => { try{ f(lang); }catch(e){} });
  }

